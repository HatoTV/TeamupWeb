#!/usr/bin/env node
// Converts the site's raster images to AVIF + WebP variants and writes a manifest used by
// the Angular image loader / srcset pipe.
//
//   public/assets/img/<path>.<ext>  ->  public/assets/img/opt/<path>-<width>.{avif,webp}
//   src/app/core/images/image-manifest.ts (generated)
//
// Widths: 1600 (heroes) and 640 (cards) for large images, 96 for icons; never upscaled.
// Usage: node tools/optimize-images.mjs [--force]

import { mkdirSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const IMG_DIR = join(ROOT, 'public', 'assets', 'img');
const OUT_DIR = join(IMG_DIR, 'opt');
const MANIFEST = join(ROOT, 'src', 'app', 'core', 'images', 'image-manifest.ts');
/** Folders replaced by Data Dragon / optimised copies, not served by the redesign. */
const SKIP_DIRS = new Set(['opt', 'championsIcons', 'championsLoadingscreen', 'rocketLeague']);
/** Small UI icons: a single 96 px variant. */
const ICON_DIRS = new Set(['icons', 'ranks', 'brand']);
const LARGE_WIDTHS = [640, 1600];
const ICON_WIDTHS = [96];
const FORCE = process.argv.includes('--force');

function* walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) yield* walk(full);
    } else if (/\.(png|jpe?g|webp)$/i.test(entry.name)) {
      yield full;
    }
  }
}

const manifest = {};
let written = 0;
let before = 0;
let after = 0;

for (const file of walk(IMG_DIR)) {
  const rel = relative(IMG_DIR, file).split(sep).join('/');
  const base = rel.slice(0, -extname(rel).length);
  const meta = await sharp(file).metadata();
  const isIcon = ICON_DIRS.has(rel.split('/')[0]) || (meta.width ?? 0) <= 160;
  const targets = (isIcon ? ICON_WIDTHS : LARGE_WIDTHS).filter((w) => w < (meta.width ?? 0));
  // Always keep one variant at the original width when it is smaller than the largest target.
  const largest = isIcon ? ICON_WIDTHS.at(-1) : LARGE_WIDTHS.at(-1);
  if ((meta.width ?? 0) <= largest) targets.push(meta.width);
  const widths = [...new Set(targets)].sort((a, b) => a - b);

  before += statSync(file).size;
  for (const width of widths) {
    for (const format of ['avif', 'webp']) {
      const out = join(OUT_DIR, `${base}-${width}.${format}`);
      if (!FORCE && existsSync(out) && statSync(out).mtimeMs >= statSync(file).mtimeMs) {
        if (width === widths.at(-1) && format === 'webp') after += statSync(out).size;
        continue;
      }
      mkdirSync(dirname(out), { recursive: true });
      const pipeline = sharp(file).resize({ width, withoutEnlargement: true });
      const info = await (format === 'avif' ? pipeline.avif({ quality: 50, effort: 4 }) : pipeline.webp({ quality: 74 })).toFile(out);
      if (width === widths.at(-1) && format === 'webp') after += info.size;
      written++;
    }
  }
  manifest[`assets/img/${rel}`] = { w: meta.width, h: meta.height, widths, opt: `assets/img/opt/${base}` };
}

mkdirSync(dirname(MANIFEST), { recursive: true });
writeFileSync(
  MANIFEST,
  `// Generated by tools/optimize-images.mjs — do not edit.\n` +
    `export interface ImageEntry {\n  /** Original width / height. */\n  w: number;\n  h: number;\n  /** Available variant widths. */\n  widths: number[];\n  /** Variant path prefix: \`\${opt}-\${width}.avif|webp\`. */\n  opt: string;\n}\n\n` +
    `export const IMAGE_MANIFEST: Record<string, ImageEntry> = ${JSON.stringify(manifest, null, 2)};\n`
);

const mb = (n) => (n / 1024 / 1024).toFixed(1);
console.log(`${Object.keys(manifest).length} images · ${written} files written`);
console.log(`Originals: ${mb(before)} MB · largest WebP variants: ${mb(after)} MB`);
